# Standard Turkish monthly abbreviations
MONTH_MAP = {
    "01": "Oca", "02": "Şub", "03": "Mar", "04": "Nis",
    "05": "May", "06": "Haz", "07": "Tem", "08": "Ağu",
    "09": "Eyl", "10": "Eki", "11": "Kas", "12": "Ara"
}

def _make_point(date_str: str, val_str: str) -> MonthlyRatioPoint:
    year, month = date_str.split("-")
    display_date = f"{MONTH_MAP.get(month, month)} {year}"
    return MonthlyRatioPoint(
        date=date_str,
        display_date=display_date,
        value=Decimal(val_str)
    )


